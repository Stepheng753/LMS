// Extracts the vscode-icons used by <FileTree> into src/components/content/fileIconData.ts,
// so the app ships ~125 icons instead of the full 3.8MB icon set.
// Re-run after editing the lists below:  node scripts/generate-file-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const set = JSON.parse(readFileSync('node_modules/@iconify-json/vscode-icons/icons.json', 'utf8'));

const files = [
  'default-file', 'file-type-js-official', 'file-type-typescript-official', 'file-type-reactjs', 'file-type-reactts',
  'file-type-python', 'file-type-java', 'file-type-class', 'file-type-c', 'file-type-cpp', 'file-type-go',
  'file-type-rust', 'file-type-php', 'file-type-ruby', 'file-type-html', 'file-type-css', 'file-type-scss',
  'file-type-json', 'file-type-yaml', 'file-type-xml', 'file-type-markdown', 'file-type-sql', 'file-type-shell',
  'file-type-log', 'file-type-text', 'file-type-pdf', 'file-type-image', 'file-type-svg', 'file-type-zip',
  'file-type-git', 'file-type-npm', 'file-type-license', 'file-type-config', 'file-type-vite',
  'file-type-tsconfig', 'file-type-docker', 'file-type-gradle', 'file-type-maven', 'file-type-excel',
];
const folders = [
  'default-folder', 'folder-type-src', 'folder-type-component', 'folder-type-config', 'folder-type-dist',
  'folder-type-docs', 'folder-type-git', 'folder-type-github', 'folder-type-images', 'folder-type-log',
  'folder-type-node', 'folder-type-public', 'folder-type-script', 'folder-type-test', 'folder-type-vscode',
  'folder-type-css', 'folder-type-style', 'folder-type-api', 'folder-type-asset', 'folder-type-hook',
  'folder-type-model', 'folder-type-view', 'folder-type-controller', 'folder-type-helper',
  'folder-type-library', 'folder-type-module', 'folder-type-temp', 'folder-type-www', 'folder-type-server',
  'folder-type-client', 'folder-type-services', 'folder-type-shared', 'folder-type-plugin',
  'folder-type-template', 'folder-type-theme', 'folder-type-tools', 'folder-type-app', 'folder-type-db',
  'folder-type-docker', 'folder-type-package', 'folder-type-python', 'folder-type-typescript', 'folder-type-js',
];

const names = [...files, ...folders.flatMap((f) => [f, `${f}-opened`])];
const out = {};
const missing = [];
for (const name of names) {
  const icon = set.icons[name] ?? (set.aliases?.[name] && set.icons[set.aliases[name].parent]);
  if (!icon) missing.push(name);
  else out[name] = icon.body;
}
if (missing.length) console.warn('Missing icons:', missing.join(', '));

const body = Object.entries(out)
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join('\n');
writeFileSync(
  'src/components/content/fileIconData.ts',
  `// GENERATED by scripts/generate-file-icons.mjs from vscode-icons (MIT). Do not edit by hand.\n// All icons use a 32x32 viewBox.\nexport const FILE_ICON_SVG: Record<string, string> = {\n${body}\n};\n`
);
console.log(`Wrote ${Object.keys(out).length} icons`);
